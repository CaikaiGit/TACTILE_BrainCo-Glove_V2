// 原点管理变量
double och1970_origin_x = 0.0;
double och1970_origin_y = 0.0;
bool och1970_origin_set = false;

// 原点设置
void och1970_set_origin(double x, double y)
{
    och1970_origin_x = x;
    och1970_origin_y = y;
    och1970_origin_set = true;
//    printf("OCH1970 Origin set: X=%.5f, Y=%.5f\r\n", x, y);
}

// 原点自动归零逻辑
void och1970_check_and_update_origin(
    double cur_x, double cur_y,
    bool* press_flag, bool* last_status,
    bool* update_pos_flag)
{
    // 按压释放或外部归零时归零
    if ((!(*press_flag) && *last_status) || *update_pos_flag)
    {
        och1970_set_origin(cur_x, cur_y);
//        printf("OCH1970 origin_set update: X=%.5f, Y=%.5f\r\n", cur_x, cur_y);
        *update_pos_flag = false;
    }
    // 按压状态变化时更新历史状态
    if (*press_flag != *last_status)
    {
        *last_status = *press_flag;
    }
}

void calc_och1970_force(const int16_t mag_raw[12], double *fx, double *fy)
{
    int16_t act_mag_data[12];
    act_mag_data[0] = mag_raw[3];
    act_mag_data[1] = mag_raw[4];
    act_mag_data[2] = -mag_raw[5];
    act_mag_data[3] = -mag_raw[0];
    act_mag_data[4] = -mag_raw[1];
    act_mag_data[5] = -mag_raw[2];
    act_mag_data[6] = -mag_raw[9];
    act_mag_data[7] = -mag_raw[10];
    act_mag_data[8] = -mag_raw[11];
    act_mag_data[9] = mag_raw[6];
    act_mag_data[10] = mag_raw[7];
    act_mag_data[11] = -mag_raw[8];

    if (act_mag_data[2] < 0) {
        for (int i = 0; i < 12; i++) act_mag_data[i] = -act_mag_data[i];
    }

    double tsl_data[12];
    tsl_data[0]  = (double)(act_mag_data[0]  - act_mag_data[3])  * 3.1e-6;
    tsl_data[1]  = (double)(act_mag_data[1]  - act_mag_data[4])  * 3.1e-6;
    tsl_data[2]  = (double)(act_mag_data[2]  - act_mag_data[5])  * 3.1e-6;
    tsl_data[3]  = (double)(act_mag_data[9]  - act_mag_data[6])  * 3.1e-6;
    tsl_data[4]  = (double)(act_mag_data[10] - act_mag_data[7])  * 3.1e-6;
    tsl_data[5]  = (double)(act_mag_data[11] - act_mag_data[8])  * 3.1e-6;
    tsl_data[6]  = (double)(act_mag_data[0]  - act_mag_data[9])  * 3.1e-6;
    tsl_data[7]  = (double)(act_mag_data[1]  - act_mag_data[10]) * 3.1e-6;
    tsl_data[8]  = (double)(act_mag_data[2]  - act_mag_data[11]) * 3.1e-6;
    tsl_data[9]  = (double)(act_mag_data[3]  - act_mag_data[6])  * 3.1e-6;
    tsl_data[10] = (double)(act_mag_data[4]  - act_mag_data[7])  * 3.1e-6;
    tsl_data[11] = (double)(act_mag_data[5]  - act_mag_data[8])  * 3.1e-6;

    *fx = -delta_calc_x_net(tsl_data);
    *fy = -delta_calc_y_net(tsl_data);
}

